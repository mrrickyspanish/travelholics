import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { WELCOME_SERIES, hasTemplate } from "../lib/email-campaign-templates";

/**
 * Emits the seed SQL for the welcome series from WELCOME_SERIES, so the rows
 * in the database cannot drift from the copy that was reviewed.
 *
 *   npm run build:campaign-seed
 *
 * The output is idempotent: safe to run more than once, and re-running after
 * a copy edit updates the subjects and delays in place.
 */

for (const step of WELCOME_SERIES.steps) {
  if (!hasTemplate(step.templateKey)) {
    throw new Error(`Step ${step.position} references a template that does not exist: ${step.templateKey}`);
  }
}

const q = (value: string) => `'${value.replace(/'/g, "''")}'`;

const sql = `-- ${WELCOME_SERIES.name}
--
-- GENERATED by \`npm run build:campaign-seed\` from WELCOME_SERIES in
-- lib/email-campaign-templates.ts. Do not hand-edit: edit the definition and
-- regenerate, so the database matches the copy that was approved.
--
-- Safe to run more than once. Re-running after a copy edit updates subject
-- lines and delays in place without disturbing anyone's progress through the
-- drip.
--
-- The campaign is created as 'draft' and SENDS NOTHING. Activating it is the
-- separate, deliberate statement at the bottom of this file.

INSERT INTO public.email_campaigns (slug, name, status)
VALUES (${q(WELCOME_SERIES.slug)}, ${q(WELCOME_SERIES.name)}, 'draft')
ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name;

${WELCOME_SERIES.steps
  .map(
    (step) => `INSERT INTO public.email_campaign_steps (campaign_id, position, delay_hours, template_key, subject)
SELECT id, ${step.position}, ${step.delayHours}, ${q(step.templateKey)}, ${q(step.subject)}
  FROM public.email_campaigns WHERE slug = ${q(WELCOME_SERIES.slug)}
ON CONFLICT (campaign_id, position)
DO UPDATE SET delay_hours  = EXCLUDED.delay_hours,
              template_key = EXCLUDED.template_key,
              subject      = EXCLUDED.subject;`,
  )
  .join("\n\n")}

-- Check what you just created:
--   SELECT s.position, s.delay_hours, s.subject
--     FROM public.email_campaign_steps s
--     JOIN public.email_campaigns c ON c.id = s.campaign_id
--    WHERE c.slug = ${q(WELCOME_SERIES.slug)}
--    ORDER BY s.position;

-- ============================================================
-- ACTIVATION -- run this only once the copy is approved.
--
-- enroll_from = now() is what stops the drip reaching back through the whole
-- existing list and mailing everyone step one at once. Set it AS you
-- activate, not before.
-- ============================================================
-- UPDATE public.email_campaigns
--    SET status = 'active', enroll_from = now()
--  WHERE slug = ${q(WELCOME_SERIES.slug)};
`;

const dir = join(process.cwd(), "supabase", "seed");
mkdirSync(dir, { recursive: true });
const out = join(dir, `${WELCOME_SERIES.slug}.sql`);
writeFileSync(out, sql);
console.log(`✓ seed written to supabase/seed/${WELCOME_SERIES.slug}.sql (${WELCOME_SERIES.steps.length} steps)`);
