import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CAMPAIGNS, hasTemplate } from "../lib/email-campaign-templates";

/**
 * Emits seed SQL for every campaign in CAMPAIGNS, so the rows in the database
 * cannot drift from the copy that was reviewed.
 *
 *   npm run build:campaign-seed
 *
 * Writes one file per campaign plus `all-campaigns.sql`. Idempotent: safe to
 * run more than once; re-running after a copy edit updates subjects and delays
 * in place. Campaigns are created as 'draft' and SEND NOTHING. Activation is a
 * separate, commented statement at the end of each file.
 */

const arr = (values: readonly string[]) => (values.length ? `ARRAY[${values.map((v) => q(v)).join(", ")}]::text[]` : "'{}'::text[]");
const q = (value: string | null) => (value === null ? "NULL" : `'${value.replace(/'/g, "''")}'`);

const files: string[] = [];
const dir = join(process.cwd(), "supabase", "seed");
mkdirSync(dir, { recursive: true });

for (const campaign of CAMPAIGNS) {
  for (const step of campaign.steps) {
    const text = [step.subject, step.preheader, step.button.label, ...step.paragraphs].join("\n");
    if (/YOLANDA TO CONFIRM/.test(text)) {
      throw new Error(`${campaign.slug} step ${step.position} still has a YOLANDA TO CONFIRM line. Resolve the copy before seeding.`);
    }
    if (!hasTemplate(step.templateKey)) {
      throw new Error(`${campaign.slug} step ${step.position} references a missing template: ${step.templateKey}`);
    }
  }

  const sql = `-- ${campaign.name}
--
-- GENERATED by \`npm run build:campaign-seed\` from lib/email-campaign-copy.ts.
-- Do not hand-edit: edit the copy file and regenerate, so the database matches
-- the copy that was approved.
--
-- Targeting: requires interest ${campaign.requiredInterest ?? "(none)"}; excludes ${campaign.excludeInterests.join(", ") || "(none)"}.
-- Created as 'draft': SENDS NOTHING until the activation statement at the end is run.

INSERT INTO public.email_campaigns (slug, name, status, required_interest, exclude_interests)
VALUES (${q(campaign.slug)}, ${q(campaign.name)}, 'draft', ${q(campaign.requiredInterest)}, ${arr(campaign.excludeInterests)})
ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name,
                                 required_interest = EXCLUDED.required_interest,
                                 exclude_interests = EXCLUDED.exclude_interests;

${campaign.steps
  .map(
    (step) => `INSERT INTO public.email_campaign_steps (campaign_id, position, delay_hours, template_key, subject)
SELECT id, ${step.position}, ${step.delayHours}, ${q(step.templateKey)}, ${q(step.subject)}
  FROM public.email_campaigns WHERE slug = ${q(campaign.slug)}
ON CONFLICT (campaign_id, position)
DO UPDATE SET delay_hours  = EXCLUDED.delay_hours,
              template_key = EXCLUDED.template_key,
              subject      = EXCLUDED.subject;`,
  )
  .join("\n\n")}

-- ============================================================
-- ACTIVATION: run only after RJ approves the copy and the start date.
-- enroll_from decides who is included: now() means only people who join from
-- here on; an earlier timestamp also includes existing subscribers who joined
-- after it (each still gets one email per hourly run, never a burst).
-- ============================================================
-- UPDATE public.email_campaigns
--    SET status = 'active', enroll_from = now()
--  WHERE slug = ${q(campaign.slug)};
`;
  const name = `${campaign.slug}.sql`;
  writeFileSync(join(dir, name), sql);
  files.push(sql);
  console.log(`✓ supabase/seed/${name} (${campaign.steps.length} steps)`);
}

writeFileSync(
  join(dir, "all-campaigns.sql"),
  `-- All nurture campaigns, generated together. Requires migration 20261110120000_add_campaign_exclude_interest.sql.\n\n${files.join("\n\n")}`,
);
console.log("✓ supabase/seed/all-campaigns.sql");
