import assert from "node:assert/strict";
import { CURATED_VIDEOS, START_HERE_IDS, videoNextStep } from "../lib/youtube-catalog";
import { PUBLISHABLE_GUIDES } from "../lib/free-guides";
import { firstLine, mergeChannelVideos, parseFeed, type Video } from "../lib/youtube";
import { buildGroupInquiryNotes, validateGroupInquiryContact } from "../lib/group-inquiry";
import { appendLeadAttribution, captureLeadAttribution, sanitizeCampaign } from "../lib/lead-attribution";

const offline = mergeChannelVideos([], CURATED_VIDEOS);
assert(offline.some((video) => video.format === "long"));
assert(offline.some((video) => video.format === "short"));
assert(START_HERE_IDS.every((id) => offline.some((video) => video.id === id)));
assert(offline.every((video) => /^[A-Za-z0-9_-]{11}$/.test(video.id)));
assert(PUBLISHABLE_GUIDES.some((guide) => `/guides/${guide.slug}` === videoNextStep("N4O_Km9eqFk").href));
const current: Video = { id: "newVideo_01", format: "long", title: "New lesson", published: "2026-10-19" };
const merged = mergeChannelVideos([current, { ...offline[0], title: "Fresh feed title", published: "2026-10-18" }, { ...current, id: "RoG1LhSLq50" }], CURATED_VIDEOS);
assert.equal(merged[0].id, current.id);
assert.equal(merged.filter((video) => video.id === offline[0].id).length, 1);
assert.equal(merged.find((video) => video.id === offline[0].id)?.title, "Fresh feed title");
assert(!merged.some((video) => video.id === "RoG1LhSLq50"));
const parsed = parseFeed('<feed><entry><yt:videoId>N4O_Km9eqFk</yt:videoId><title>Packing &amp; planning</title><published>2026-07-13</published></entry><entry><yt:videoId>../../bad</yt:videoId></entry></feed>');
assert.equal(parsed.length, 1);
assert.equal(parsed[0].title, "Packing & planning");

assert.equal(firstLine("Plan with Yolanda: https://yotravelholic.com/group-cruises?utm_source=youtube"), "Plan with Yolanda");
assert.equal(firstLine("https://example.com/?utm_source=youtube\nChoose your ship."), "Choose your ship.");
assert.equal(firstLine("\nwww.example.com\n"), undefined);
assert.equal(firstLine("[Cruise advice](https://example.com)"), "Cruise advice");
assert.equal(firstLine("Choose a cruise with confidence", 20), "Choose a cruise…");
assert.equal(firstLine("Supercalifragilistic", 8), "…");

const base = { leaderName: "Example Organizer", email: "example@example.com", groupType: "Family reunion", preferredContact: "email" };
assert.equal(validateGroupInquiryContact(base), null);
assert(validateGroupInquiryContact({ ...base, preferredContact: "phone" }));
assert(validateGroupInquiryContact({ ...base, preferredContact: "text", phone: "3125550100" }));
assert.equal(validateGroupInquiryContact({ ...base, preferredContact: "text", phone: "3125550100", smsConsent: true }), null);
assert(validateGroupInquiryContact({ ...base, estimatedCabins: "2.5" }));
assert(validateGroupInquiryContact({ ...base, estimatedGroupSize: 1 }));
assert.equal(validateGroupInquiryContact({ ...base, estimatedGroupSize: null, estimatedCabins: "" }), null);
const details = buildGroupInquiryNotes({ estimatedCabins: 8, budgetPerPerson: "$1,500-$2,000", notes: "Accessible cabin requested.\nReferral: utm_source=youtube" });
assert(details.includes("Estimated cabins: 8"));
assert(details.includes("before flights"));
assert(details.includes("Accessible cabin requested."));
assert(details.includes("utm_source=youtube"));

assert.deepEqual(sanitizeCampaign({ utm_source: "youtube", unrelated: "ignored", utm_campaign: "<bad>\nvalue" }), { utm_source: "youtube", utm_campaign: "badvalue" });
assert.equal(captureLeadAttribution().utm_source, undefined);
const data = new Map<string, string>();
const fakeWindow = { location: { search: "?utm_source=tiktok&utm_medium=bio&utm_campaign=group_cruises" }, sessionStorage: { getItem: (key: string) => data.get(key) ?? null, setItem: (key: string, value: string) => { data.set(key, value); } } };
Object.defineProperty(globalThis, "window", { configurable: true, value: fakeWindow });
assert.equal(captureLeadAttribution().utm_source, "tiktok");
fakeWindow.location.search = "";
assert(appendLeadAttribution("Family reunion").includes("utm_source=tiktok"));
fakeWindow.sessionStorage.getItem = () => { throw new Error("Storage disabled"); };
fakeWindow.location.search = "?utm_source=youtube";
assert.equal(captureLeadAttribution().utm_source, "youtube");
delete (globalThis as { window?: unknown }).window;
console.log("Growth funnel checks passed: feed outage, catalog freshness, expired offer, group contact/qualification, and campaign continuity.");
